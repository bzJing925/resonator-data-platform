import { test, expect } from '@playwright/test';
import { mkdtemp, readFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
test.use({ baseURL: 'http://127.0.0.1:5173' });
test('actual Plotly PNG report opens offline without network or executable notes and prints landscape', async ({ page, browser }, info) => {
  await page.goto('/e2e/analysis/report.html');
  await page.getByRole('button', { name: '加载报告夹具' }).click();
  const reportStart = Date.now();
  await page.getByRole('button', { name: '生成HTML报告' }).click();
  const pending = page.waitForEvent('download');
  await page.getByRole('button', { name: '下载离线HTML' }).click();
  const download = await pending;
  await info.attach('report-generation-time.json', { body: JSON.stringify({ elapsedMs: Date.now() - reportStart }), contentType: 'application/json' });
  const dir = await mkdtemp(path.join(os.tmpdir(), 'aln-report-'));
  const file = path.join(dir, 'report.html'); await download.saveAs(file);
  const content = await readFile(file, 'utf8');
  expect(content).toContain('data:image/png;base64,'); expect(content).not.toContain('<script>');
  const context = await browser.newContext({ offline: true }), offline = await context.newPage();
  const requests: string[] = []; offline.on('request', (request) => { if (/^https?:/.test(request.url())) requests.push(request.url()); });
  await offline.goto(pathToFileURL(file).href);
  await expect(offline.locator('figure img')).toHaveCount(1);
  expect(await offline.locator('figure img').evaluate((image: HTMLImageElement) => [image.complete, image.naturalWidth, image.naturalHeight])).toEqual([true, 1600, 1000]);
  await expect(offline.getByText('<script>window.evil=true;fetch("https://bad.test")</script><img src=x onerror=alert(1)>', { exact: true })).toBeVisible();
  expect(await offline.evaluate(() => (window as any).evil)).toBeUndefined(); expect(requests).toEqual([]);
  await offline.emulateMedia({ media: 'print' });
  expect(await offline.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
  const pdf = await offline.pdf({ path: path.join(dir, 'report.pdf'), preferCSSPageSize: true, printBackground: true });
  expect(pdf.length).toBeGreaterThan(10000); expect(pdf.toString('latin1')).toContain('/MediaBox [0 0 841');
  await context.close();
});

import { test, expect } from '@playwright/test';
import { readFile, mkdtemp, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

test('real customer snapshot preserves full rows, unknown fields, CSV and offline PNG report', async ({ page, browser }, info) => {
  test.skip(!process.env.ALN_CUSTOMER_SNAPSHOT_JSON, 'Opt-in original customer snapshot required');
  test.setTimeout(120000);
  const source = JSON.parse(await readFile(process.env.ALN_CUSTOMER_SNAPSHOT_JSON!, 'utf8'));
  const dir = await mkdtemp(join(tmpdir(), 'aln-customer-report-'));
  await page.goto('http://127.0.0.1:5173/e2e/analysis/report.html');
  await page.waitForFunction(() => 'customerReport' in window);
  await page.evaluate((rows) => (window as any).customerReport.load(rows), source.rows);
  await expect(page.getByTestId('project-save-status')).toContainText('已保存');
  await page.reload();
  await page.waitForFunction(() => (window as any).customerReport?.rows.length === 7553);
  const restored = await page.evaluate(() => (window as any).customerReport.rows);
  const originalColumns = Object.keys(source.rows[0]);
  expect(restored.map((row: Record<string, unknown>) => Object.fromEntries(
    originalColumns.map((key) => [key, row[key]])))).toEqual(source.rows);
  expect(restored.filter((r: any) => r.Type === null)).toHaveLength(7349);
  const summaries = await page.evaluate(() => (window as any).customerReport.frozen());
  expect(summaries[0].manifest.returned).toBe(7553);
  expect(summaries[0].manifest.consistency).toBe('unverified');
  expect(summaries[0].statistics.qs.valid_n).toBe(7553);
  const mean = source.rows.reduce((sum: number, row: any) => sum + row.qs, 0) / 7553;
  expect(summaries[0].statistics.qs.mean).toBeCloseTo(mean, 8);
  const csv = await page.evaluate(() => (window as any).customerReport.csv());
  await writeFile(join(dir, 'customer-workspace.csv'), csv);
  expect(csv.trim().split('\r\n')).toHaveLength(7554);
  expect(source.rows.every((row: any) => csv.includes(row.original_filename))).toBe(true);
  await page.getByRole('button', { name: '生成HTML报告' }).click();
  await page.getByLabel('报告标题').fill('客户结果快照验收');
  const pending = page.waitForEvent('download');
  await page.getByRole('button', { name: '下载离线HTML' }).click();
  const html = join(dir, 'customer-report.html'); await (await pending).saveAs(html);
  const context = await browser.newContext({ offline: true }), offline = await context.newPage();
  const requests: string[] = [];
  offline.on('request', (r) => { if (/^https?:/.test(r.url())) requests.push(r.url()); });
  await offline.goto(pathToFileURL(html).href);
  await expect(offline.locator('figure img')).toHaveCount(1);
  expect(await offline.locator('figure img').evaluate((img: HTMLImageElement) => img.complete && img.naturalWidth === 1600)).toBe(true);
  await expect(offline.getByText('客户结果表快照；原始ZIP已删除，算法及处理频段未知，不包含原始曲线。', { exact: true })).toBeVisible();
  expect(JSON.parse(await offline.locator('pre').first().innerText())[0].statistics.qs.valid_n).toBe(7553);
  expect(requests).toEqual([]);
  await offline.screenshot({ path: join(dir, 'customer-report.png'), fullPage: true });
  await offline.emulateMedia({ media: 'print' });
  const pdf = await offline.pdf({ path: join(dir, 'customer-report.pdf'), preferCSSPageSize: true });
  expect(pdf.length).toBeGreaterThan(10000);
  await info.attach('customer-snapshot.json', { body: JSON.stringify({ rows: restored.length, source_sha256: source.source_sha256, summaries, artifacts: dir }), contentType: 'application/json' });
  await context.close();
});
